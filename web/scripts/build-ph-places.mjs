/**
 * Generates src/lib/phPlaces.ts: every Philippine city, municipality and
 * province as "Place, Province" labels, used to suggest destinations.
 *
 * Source: Philippine Standard Geographic Code (PSGC) via https://psgc.gitlab.io
 * Run: node scripts/build-ph-places.mjs   (only needed to refresh the list)
 */
import { writeFileSync } from 'node:fs';

const API = 'https://psgc.gitlab.io/api';
const OUTPUT = new URL('../src/lib/phPlaces.ts', import.meta.url);

// Cities outside any province in the PSGC, placed by geography instead.
const NO_PROVINCE = { '130000000': 'Metro Manila' };
const INDEPENDENT = { 'City of Isabela': 'Basilan', 'City of Cotabato': 'Maguindanao del Norte', 'Cotabato City': 'Maguindanao del Norte' };

const get = async (path) => {
  const response = await fetch(`${API}/${path}.json`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.json();
};

// PSGC capitalises particles ("Agusan Del Norte"); the usual spelling is lowercase.
const fixParticles = (name) => name.replace(/(?<=\S )(De La|Del|De)(?= )/g, (p) => p.toLowerCase());

// "City of Tacloban" -> "Tacloban City"; "Tacloban City" stays.
function displayName(name) {
  const cityOf = /^City of (.+)$/.exec(name);
  return fixParticles(cityOf ? `${cityOf[1]} City` : name);
}

const [places, provinces] = await Promise.all([get('cities-municipalities'), get('provinces')]);
const provinceName = new Map(provinces.map((p) => [p.code, fixParticles(p.name)]));

const labels = new Set();
for (const place of places) {
  const province =
    (place.provinceCode && provinceName.get(place.provinceCode)) ||
    INDEPENDENT[place.name] ||
    NO_PROVINCE[place.regionCode];
  const name = displayName(place.name);
  labels.add(province ? `${name}, ${province}` : name);
}
for (const province of provinces) labels.add(fixParticles(province.name));
labels.add('Metro Manila');

const sorted = [...labels].sort((a, b) => a.localeCompare(b));
writeFileSync(
  OUTPUT,
  `// Generated by scripts/build-ph-places.mjs from the PSGC. Do not edit.
// ${sorted.length} cities, municipalities and provinces.
export const PH_PLACES: readonly string[] = ${JSON.stringify(sorted)};
`,
);
console.log(`Wrote ${sorted.length} places`);
